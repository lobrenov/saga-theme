// Writes theme.css: @font-face rules with the woff2 files embedded, then src/theme.css.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { stdout } from 'node:process'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))

const latin =
  'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD'

const fonts = [
  { family: 'Fraunces Variable', style: 'normal', weight: '100 900', file: 'fraunces-latin-opsz-normal', format: 'woff2-variations' },
  { family: 'Fraunces Variable', style: 'italic', weight: '100 900', file: 'fraunces-latin-opsz-italic', format: 'woff2-variations' },
  { family: 'Source Serif 4 Variable', style: 'normal', weight: '200 900', file: 'source-serif-4-latin-opsz-normal', format: 'woff2-variations' },
  { family: 'Source Serif 4 Variable', style: 'italic', weight: '200 900', file: 'source-serif-4-latin-opsz-italic', format: 'woff2-variations' },
  { family: 'IBM Plex Sans', style: 'normal', weight: '400', file: 'ibm-plex-sans-latin-400-normal', format: 'woff2' },
  { family: 'IBM Plex Sans', style: 'normal', weight: '500', file: 'ibm-plex-sans-latin-500-normal', format: 'woff2' },
  { family: 'IBM Plex Sans', style: 'normal', weight: '600', file: 'ibm-plex-sans-latin-600-normal', format: 'woff2' },
  { family: 'IBM Plex Mono', style: 'normal', weight: '400', file: 'ibm-plex-mono-latin-400-normal', format: 'woff2' },
  { family: 'IBM Plex Mono', style: 'normal', weight: '500', file: 'ibm-plex-mono-latin-500-normal', format: 'woff2' }
]

const header = `/* Saga theme for Obsidian. Generated by build.mjs; edit src/theme.css.
 * Embedded fonts (latin subsets), each under the SIL Open Font License 1.1 (fonts/LICENSE-*.txt):
 * Fraunces, (c) 2020 The Fraunces Project Authors; Source Serif 4, (c) Google Inc.;
 * IBM Plex Sans and IBM Plex Mono, (c) IBM Corp. */\n`

const faces = fonts
  .map(({ family, style, weight, file, format }) => {
    const data = readFileSync(join(root, 'fonts', `${file}.woff2`)).toString('base64')
    return `@font-face{font-family:'${family}';font-style:${style};font-weight:${weight};font-display:swap;src:url(data:font/woff2;base64,${data}) format('${format}');unicode-range:${latin}}`
  })
  .join('\n')

const source = readFileSync(join(root, 'src', 'theme.css'), 'utf8')
writeFileSync(join(root, 'theme.css'), `${header}${faces}\n${source}`)
stdout.write(`theme.css written (${fonts.length} fonts)\n`)
